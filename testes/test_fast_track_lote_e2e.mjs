import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const {chromium} = await import(process.env.CCAA_PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.CCAA_TEST_URL, evidence = process.env.CCAA_EVIDENCE;
await mkdir(evidence, {recursive: true});
const browser = await chromium.launch({headless: true,
  executablePath: process.env.AGENT_BROWSER_EXECUTABLE_PATH || '/opt/hermes/tools/chromium-1208/chrome-linux64/chrome'});
try {
  const page = await browser.newPage({viewport: {width: 1440, height: 1050}, acceptDownloads: true});
  const errors = [], external = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    if (/^https?:/.test(request.url()) && new URL(request.url()).origin !== base) external.push(request.url());
  });
  await page.goto(base + '/fast-track-infra-2026/lote');
  assert.equal(await page.locator('#batch-load-fast-track').count(), 1, 'mapped batch loading exists');
  let releaseLoad, loaded;
  const gate = new Promise(resolve => { releaseLoad = resolve; });
  const waiting = new Promise(resolve => { loaded = resolve; });
  await page.route('**/api/lote/fast-track', async route => {
    const response = await route.fetch();
    loaded(); await gate; await route.fulfill({response});
  });
  await page.locator('#batch-load-fast-track').click();
  await waiting;
  await page.locator('#batch-approved').check();
  releaseLoad();
  await page.locator('[data-row]').nth(2).waitFor();
  assert.equal(await page.locator('#batch-approved').isChecked(), false, 'loaded source rows need fresh approval');
  await page.unroute('**/api/lote/fast-track');
  assert.equal(await page.locator('[data-row]').count(), 3);
  assert.equal(await page.locator('[data-field=selecionado]:checked').count(), 0);
  assert.equal(await page.locator('#batch-html').getAttribute('required'), null);
  assert.equal(await page.locator('#batch-xlsx').getAttribute('required'), null);
  await page.locator('#batch-search').fill('Polo B');
  assert.equal(await page.locator('[data-row]:visible').count(), 1);
  await page.locator('#batch-select-visible').click();
  assert.equal(await page.locator('[data-field=selecionado]:checked').count(), 1);
  const academic = page.locator('[data-row="1"] [data-field=academico_nome]');
  assert.equal(await academic.inputValue(), '');
  await page.locator('#batch-subject').fill('Fast Track QA');
  await page.locator('#batch-approved').check();
  await page.locator('#batch-build').click();
  assert.equal(await academic.evaluate(element => element.validity.valueMissing), true, 'academic missing blocks download');
  await academic.selectOption({label: 'Acadêmico — academico@example.test'});
  assert.equal(await page.locator('#batch-approved').isChecked(), false);
  await page.locator('#batch-search').fill('Polo A');
  await page.locator('#batch-select-visible').click();
  assert.equal(await page.locator('[data-field=selecionado]:checked').count(), 2, 'selection across filters is retained');
  await page.locator('#batch-search').fill('');
  await page.locator('#batch-preview-button').click();
  await page.waitForFunction(() => document.querySelector('#batch-preview').getAttribute('src')?.startsWith('/api/preview/'));
  await page.locator('#batch-approved').check();
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#batch-build').click();
  const download = await downloadPromise;
  await download.saveAs(evidence + '/fast-track-synthetic.zip');
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Pacote baixado'));
  assert.equal(await page.locator('[data-row="2"] [data-field=para]').inputValue(), '');
  await page.locator('#batch-search').fill('Polo sem cadastro');
  await page.locator('#batch-select-visible').click();
  assert.equal(await page.locator('[data-row="2"] [data-field=para]').evaluate(element => element.required), true);
  await page.locator('#batch-clear-selection').click();
  assert.equal(await page.locator('[data-field=selecionado]:checked').count(), 0);
  assert.equal(await page.locator('#batch-build').isDisabled(), true);
  await page.locator('#batch-search').fill('');
  await page.locator('[data-row="0"]').scrollIntoViewIfNeeded();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.screenshot({path: evidence + '/fast-track-lote-desktop.png', fullPage: true});
  await page.setViewportSize({width: 390, height: 844});
  await page.locator('[data-row="0"]').scrollIntoViewIfNeeded();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('[data-row="0"]').screenshot({path: evidence + '/fast-track-lote-polo-mobile.png'});
  await page.screenshot({path: evidence + '/fast-track-lote-mobile.png', fullPage: true});
  await page.reload();
  assert.equal(await page.locator('[data-row]').count(), 0, 'no persistence in browser');
  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
  console.log(JSON.stringify({result: 'PASS', flow: 'mapped-fast-track', rows: 3, errors, external}));
} finally {
  await browser.close();
}
