import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const {chromium} = await import(process.env.CCAA_PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.CCAA_TEST_URL, evidence = process.env.CCAA_EVIDENCE;
await mkdir(evidence, {recursive: true});
const browser = await chromium.launch({headless: true,
  executablePath: process.env.AGENT_BROWSER_EXECUTABLE_PATH || '/opt/hermes/tools/chromium-1208/chrome-linux64/chrome'});
try {
  const page = await browser.newPage({viewport: {width: 1440, height: 1050}, acceptDownloads: true});
  const errors = [], external = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    if (/^https?:/.test(request.url()) && new URL(request.url()).origin !== base) external.push(request.url());
  });
  await page.goto(base + '/fast-track-infra-2026/lote');
  assert.equal(await page.locator('#batch-load-fast-track').count(), 1, 'mapped batch loading exists');
  assert.equal(await page.locator('#batch-load-fast-track').textContent(), 'Carregar polos com checklist pendente');
  assert.ok((await page.locator('#batch-form').textContent()).includes('20/11/2026'));
  assert.ok(!(await page.locator('#batch-form').textContent()).includes('31/08'));
  let releaseLoad, loaded;
  const gate = new Promise(resolve => { releaseLoad = resolve; });
  const waiting = new Promise(resolve => { loaded = resolve; });
  await page.route('**/api/lote/fast-track', async route => {
    const response = await route.fetch();
    loaded(); await gate; await route.fulfill({response});
  });
  await page.locator('#batch-load-fast-track').click();
  await waiting;
  await page.locator('#batch-approved').check();
  releaseLoad();
  await page.locator('[data-row]').nth(2).waitFor();
  assert.equal(await page.locator('#batch-approved').isChecked(), false, 'loaded source rows need fresh approval');
  await page.unroute('**/api/lote/fast-track');
  assert.equal(await page.locator('[data-row]').count(), 3);
  assert.equal(await page.locator('[data-field=selecionado]:checked').count(), 0);
  assert.equal(await page.locator('#batch-subject').isDisabled(), true, 'mapped rows already have per-polo subjects');
  const prefix = '[ PREENCHIMENTO OBRIGATÓRIO - CL INSUMOS e CL REVENUE SHARE] Novo prazo máximo para preenchimento - ';
  assert.equal(await page.locator('[data-row="0"] [data-field=assunto]').inputValue(), prefix + 'Polo A');
  assert.ok((await page.locator('[data-row="1"]').textContent()).includes('Checklist de laboratório e Checklist de infraestrutura'));
  assert.equal(await page.locator('#batch-html').getAttribute('required'), null);
  assert.equal(await page.locator('#batch-xlsx').getAttribute('required'), null);
  await page.locator('#batch-search').fill('Polo B');
  assert.equal(await page.locator('[data-row]:visible').count(), 1);
  await page.locator('#batch-select-visible').click();
  assert.equal(await page.locator('[data-field=selecionado]:checked').count(), 1);
  const academic = page.locator('[data-row="1"] [data-field=academico_nome]');
  assert.equal(await academic.inputValue(), '');

  await page.locator('#batch-approved').check();
  await page.locator('#batch-build').click();
  assert.equal(await academic.evaluate(element => element.validity.valueMissing), true, 'academic missing blocks download');
  await academic.selectOption({label: 'Acadêmico — academico@example.test'});
  assert.equal(await page.locator('#batch-approved').isChecked(), false);
  await page.locator('#batch-search').fill('Polo A');
  await page.locator('#batch-select-visible').click();
  assert.equal(await page.locator('[data-field=selecionado]:checked').count(), 2, 'selection across filters is retained');
  await page.locator('#batch-search').fill('');
  await page.locator('#batch-preview-button').click();
  await page.waitForFunction(() => document.querySelector('#batch-preview').getAttribute('src')?.startsWith('/api/preview/'));
  await page.locator('#batch-approved').check();
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#batch-build').click();
  const download = await downloadPromise;
  await download.saveAs(evidence + '/fast-track-synthetic.zip');
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Pacote baixado'));
  assert.equal(await page.locator('[data-row="2"] [data-field=para]').inputValue(), '');
  await page.locator('#batch-search').fill('Polo sem cadastro');
  await page.locator('#batch-select-visible').click();
  assert.equal(await page.locator('[data-row="2"] [data-field=para]').evaluate(element => element.required), true);
  await page.locator('#batch-clear-selection').click();
  assert.equal(await page.locator('[data-field=selecionado]:checked').count(), 0);
  assert.equal(await page.locator('#batch-build').isDisabled(), true);
  await page.locator('#batch-search').fill('');
  await page.locator('[data-row="0"]').scrollIntoViewIfNeeded();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.screenshot({path: evidence + '/fast-track-lote-desktop.png', fullPage: true});
  await page.setViewportSize({width: 390, height: 844});
  await page.locator('[data-row="0"]').scrollIntoViewIfNeeded();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('[data-row="0"]').screenshot({path: evidence + '/fast-track-lote-polo-mobile.png'});
  await page.screenshot({path: evidence + '/fast-track-lote-mobile.png', fullPage: true});
  await page.setViewportSize({width: 1440, height: 1050});
  assert.equal(await page.locator('#batch-add-row').isVisible(), true, 'loaded list offers manual addition');
  await page.locator('#batch-approved').check();
  await page.locator('#batch-search').fill('não encontra nenhum');
  await page.locator('#batch-add-row').click();
  assert.equal(await page.locator('[data-row]').count(), 4);
  assert.equal(await page.locator('#batch-search').inputValue(), '');
  assert.equal(await page.locator('#batch-approved').isChecked(), false);
  const added = page.locator('[data-row="3"]');
  assert.equal(await added.locator('[data-field=polo]').evaluate(el => el === document.activeElement), true);
  await added.locator('[data-field=polo]').fill('Novo polo');
  assert.equal(await added.locator('[data-field=assunto]').inputValue(), prefix + 'Novo polo');
  await added.locator('[data-field=para]').fill('novo@example.test');
  await added.locator('[data-field=cc]').fill('copia@example.test');
  await added.locator('[data-field=academico_nome]').selectOption('Acadêmico');
  await added.locator('[data-field=selecionado]').check();
  const first = page.locator('[data-row="0"]');
  await first.locator('[data-field=polo]').fill('Polo corrigido');
  assert.equal(await first.locator('legend').textContent(), 'Linha 1 — Polo corrigido');
  assert.equal(await first.locator('[data-field=assunto]').inputValue(), prefix + 'Polo corrigido');
  await first.locator('[data-field=assunto]').fill('Assunto revisado');
  await first.locator('[data-field=polo]').fill('Polo corrigido final');
  assert.equal(await first.locator('[data-field=assunto]').inputValue(), 'Assunto revisado');
  await first.locator('[data-field=selecionado]').check();
  page.once('dialog', dialog => dialog.dismiss());
  await first.getByRole('button', {name: 'Excluir Polo corrigido final', exact: true}).click();
  assert.equal(await page.locator('[data-row]').count(), 4, 'canceled delete preserves row');
  await page.locator('#batch-approved').check();
  page.once('dialog', dialog => dialog.accept());
  await first.getByRole('button', {name: 'Excluir Polo corrigido final', exact: true}).click();
  assert.equal(await page.locator('[data-row]').count(), 3);
  assert.equal(await page.locator('#batch-approved').isChecked(), false);
  assert.equal(await page.locator('[data-row="2"] [data-field=para]').inputValue(), 'novo@example.test', 'rerender retains manual edits');
  await page.locator('#batch-approved').check();
  const editedRequest = page.waitForRequest('**/api/lote/fast-track/pacote');
  const editedDownload = page.waitForEvent('download');
  await page.locator('#batch-build').click();
  const submitted = (await editedRequest).postDataJSON();
  assert.deepEqual(submitted.rows.filter(row => row.selecionado).map(row => row.polo), ['Novo polo']);
  await (await editedDownload).saveAs(evidence + '/fast-track-edited.zip');
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Pacote baixado'));
  let releasePackage, packageFetched;
  const packageGate = new Promise(resolve => { releasePackage = resolve; });
  const packageWaiting = new Promise(resolve => { packageFetched = resolve; });
  await page.route('**/api/lote/fast-track/pacote', async route => {
    const response = await route.fetch();
    packageFetched(); await packageGate; await route.fulfill({response});
  });
  let staleDownloads = 0;
  const countStaleDownload = () => { staleDownloads++; };
  page.on('download', countStaleDownload);
  const staleResponse = page.waitForResponse('**/api/lote/fast-track/pacote');
  await page.locator('#batch-build').click();
  await packageWaiting;
  page.once('dialog', dialog => dialog.accept());
  await page.locator('[data-row="2"] [data-action=delete]').click();
  assert.equal(await page.locator('#batch-approved').isChecked(), false);
  releasePackage();
  const response = await staleResponse;
  await response.finished();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert.equal(staleDownloads, 0, 'deleting while export is pending must prevent stale download');
  assert.equal(await page.locator('#batch-build').isDisabled(), true);
  page.off('download', countStaleDownload);
  await page.unroute('**/api/lote/fast-track/pacote');
  for (let remaining = 2; remaining; remaining--) {
    page.once('dialog', dialog => dialog.accept());
    await page.locator('[data-row="0"] [data-action=delete]').click();
  }
  assert.equal(await page.locator('#batch-build').isDisabled(), true);
  assert.equal(await page.locator('#batch-add-row').isVisible(), true, 'can recover an empty roster');
  await page.locator('#batch-add-row').click();
  assert.equal(await page.locator('[data-row]').count(), 1);
  await page.reload();
  assert.equal(await page.locator('[data-row]').count(), 0, 'no persistence in browser');
  assert.equal(await page.locator('#batch-add-row').isHidden(), true);
  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
  console.log(JSON.stringify({result: 'PASS', flow: 'mapped-fast-track', rows: 3, errors, external}));
} finally {
  await browser.close();
}
